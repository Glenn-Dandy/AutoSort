use OCA\AutoSort\Service\RuleMatcher as M;
$d =fn ($x) => $x?->format('Y-m-d');
check('term spaces', M::containsTerm("Nr.  123\n456 789", '123 456 789'), true);
check('term joined', M::containsTerm('AB-CD123', 'AB-CD 123'), true);
check('term case', M::containsTerm('BEITRAGSRECHNUNG', 'Beitragsrechnung'), true);
check('term umlaut case', M::containsTerm('ÄNDERUNG', 'änderung'), true);
check('grouped number', M::containsTerm('Nr. 123 456 789', '123456789'), true);
check('letters stay words', M::containsTerm('Kolb auch', 'Bau'), false);
check('wrong number', M::containsTerm('AB-CD 123', 'AB-CD 132'), false);
check('term absent', M::containsTerm('AB-CD 999', 'AB-CD 123'), false);
check('term regex chars', M::containsTerm('abc', 'a.c'), false);
check('blank term', M::containsTerm('abc', '   '), false);
check('first date', $d(M::findDate("Musterstadt, 23.11.2024\nAm 01.01.2025")), '2024-11-23');
check('skip invalid', $d(M::findDate('99.99.2024 dann 05.03.2024')), '2024-03-05');
check('short date', $d(M::findDate('am 1.2.2025')), '2025-02-01');
check('written month', $d(M::findDate('den 3. März 2024')), '2024-03-03');
check('full month', $d(M::findDate('Musterstadt, 8. Juli 2026')), '2026-07-08');
check('lower case month', $d(M::findDate('den 8. juli 2026')), '2026-07-08');
check('upper case month', $d(M::findDate('8. MÄRZ 2026')), '2026-03-08');
check('leading zero with month', $d(M::findDate('08. Juni 2026')), '2026-06-08');
