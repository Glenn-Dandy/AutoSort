<?php
require __DIR__ . '/bootstrap.php';
require __DIR__ . '/../lib/Service/RuleMatcher.php';
use OCA\AutoSort\Service\RuleMatcher as M;
$d =fn ($x) => $x?->format('Y-m-d');
check('term spaces', M::containsTerm("Nr.  123\n456 789", '123 456 789'), true);
check('term joined', M::containsTerm('AB-CD123', 'AB-CD 123'), true);
check('term case', M::containsTerm('BEITRAGSRECHNUNG', 'Beitragsrechnung'), true);
check('term umlaut case', M::containsTerm('ÄNDERUNG', 'änderung'), true);
check('grouped number', M::containsTerm('Nr. 123 456 789', '123456789'), true);
check('letters stay words', M::containsTerm('Kolb auch', 'Bau'), false);
check('wrong number', M::containsTerm('AB-CD 123', 'AB-CD 132'), false);
check('term absent', M::containsTerm('AB-CD 999', 'AB-CD 123'), false);
check('term regex chars', M::containsTerm('abc', 'a.c'), false);
check('blank term', M::containsTerm('abc', '   '), false);
check('first date', $d(M::findDate("Musterstadt, 23.11.2024\nAm 01.01.2025")), '2024-11-23');
check('skip invalid', $d(M::findDate('99.99.2024 dann 05.03.2024')), '2024-03-05');
check('short date', $d(M::findDate('am 1.2.2025')), '2025-02-01');
check('written month', $d(M::findDate('den 3. März 2024')), '2024-03-03');
check('date after', $d(M::findDate('Beginn 01.01.2020 Rechnungsdatum: 14.10.2026', 'Rechnungsdatum')), '2026-10-14');
check('date after absent', M::findDate('01.01.2020', 'Rechnungsdatum'), null);
check('no date in number', M::findDate('123.11.20245'), null);
$date = new DateTimeImmutable('2024-11-23');
check('name', M::buildFilename('{Datum}_123456789_Beitragsrechnung.pdf', $date, 'scan 1.pdf'), '2024.11.23_123456789_Beitragsrechnung.pdf');
check('date block', M::buildFilename('{JJJJ.MM.TT}_x.pdf', $date, 'a.pdf'), '2024.11.23_x.pdf');
check('date block german', M::buildFilename('{TT.MM.JJJJ} {Original}', $date, 'a.pdf'), '23.11.2024 a.pdf');
check('date block compact', M::buildFilename('{JJJJMMTT}', $date, 'a.pdf'), '20241123.pdf');
check('usesDate block', M::usesDate('{JJJJ-MM-TT}.pdf'), true);
check('hit', M::buildFilename('{JJJJ.MM.TT}_{Treffer}.pdf', $date, 'a.pdf', 'Einheitswertbescheid'), '2024.11.23_Einheitswertbescheid.pdf');
check('hit slash', M::buildFilename('{Treffer}', null, 'a.pdf', 'A/B'), 'A-B.pdf');
check('name no ext', M::buildFilename('{Jahr}-{Monat}-{Tag} Brief', $date, 'x.pdf'), '2024-11-23 Brief.pdf');
check('name original', M::buildFilename('{Datum}_{Original}', $date, 'scan.PDF'), '2024.11.23_scan.pdf');
check('blank keeps', M::buildFilename(' ', null, 'scan.pdf'), 'scan.pdf');
check('slash stripped', M::buildFilename('a/b\\c', null, 'x.pdf'), 'a-b-c.pdf');
check('usesDate', M::usesDate('{Original}.pdf'), false);
check('usesDate 2', M::usesDate('x/{Jahr}'), true);
finish();
