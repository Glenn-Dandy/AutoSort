check('hit slash', M::buildFilename('{Treffer}', null, 'a.pdf', 'A/B'), 'A-B.pdf');
check('name no ext', M::buildFilename('{Jahr}-{Monat}-{Tag} Brief', $date, 'x.pdf'), '2024-11-23 Brief.pdf');
check('name original', M::buildFilename('{Datum}_{Original}', $date, 'scan.PDF'), '2024.11.23_scan.pdf');
check('blank keeps', M::buildFilename(' ', null, 'scan.pdf'), 'scan.pdf');
check('slash stripped', M::buildFilename('a/b\\c', null, 'x.pdf'), 'a-b-c.pdf');
